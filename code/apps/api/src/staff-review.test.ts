const writer: EvidenceWriter = {
  bucket: 'ankanu',
  async writeObject(key, body) {
    objects.set(key, Buffer.from(body))
  },
  async readObject(key) {
    const stored = objects.get(key)
    if (!stored) {
      throw new Error('missing object')
    }
    return stored
  },
}

/** A synthetic JPEG-signed blob, unique per call. */
function fakeJpeg(tag: string): Buffer {
  return Buffer.concat([Buffer.from([0xff, 0xd8, 0xff, 0xe0]), Buffer.from(`synthetic-${tag}-${serial}`), Buffer.from([0xff, 0xd9])])
}

function samplePng(shade: number): Buffer {
  const png = new PNG({ width: 8, height: 8 })
  png.data.fill(shade)
  return PNG.sync.write(png)
}

function advance(ms: number): void {
  now = new Date(now.getTime() + ms)
}

function cookieOf(response: Response): string {
  const match = /ankanu_session=([^;]+)/.exec(response.headers.getSetCookie().join('\n'))
  expect(match?.[1]).toBeTruthy()
  return `ankanu_session=${match?.[1] ?? ''}`
}

